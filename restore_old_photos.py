# ------------------------------------------------- 4MP 画幅（按各自原图比例等比）
# ⚠️ 按原图比例算，"去边框后铺满"才不会让模型拉伸变形。
#   尺寸对齐 32 的倍数（Qwen 建议）。4.0 MP ≈ 官方 2K 档的 2048²。
SIZES = {
    #old1 1280x1706 = 0.7503  → 3:4
    "old1_handheld.jpg":      (1760, 2368),
    # old2 473x800 = 0.5913（拍立得）
    "old2_handheld_glare.jpg": (1568, 2656),
    # old3 670x502 = 1.3347
    "old3_handheld_stamp.jpg": (2368, 1776),
    # old4 同 old3
    "old4_digital_stamp.jpg": (2368, 1776),
    # old5 600x800 = 0.75 → 3:4
    "old5_digital_stamp.jpg": (1760, 2368),
}

STEPS = 15# 4MP 比1MP 吃步数，10 步细节偏软


def build_prompt(name: str) -> str:
    return "\n\n".join([FILL_FRAME, RESTORE, EXTRA[name]])


def run(name: str) -> int:
    src = os.path.join(IN, name)
    stem = os.path.splitext(name)[0]
    out = os.path.join(HERE, "out", "restore_%s.png" % stem)
    w, h = SIZES[name]
    mp = w * h / 1048576
    print("\n" + "=" * 70)
    print("[%s]  %.2fMP  %dx%d  steps=%d" % (name, mp, w, h, STEPS))
    print("=" * 70)
    cmd = [PY, CG, "i2i",
           "--src", src,
           "--prompt", build_prompt(name),
           "--out", out,
           "--width", str(w), "--height", str(h),
           "--steps", str(STEPS),
           "--cfg", "1.0",
           "--sampler", "euler", "--scheduler", "simple",
           "--cache-device", "cpu",
           "--seed", "20261005",
           "--prefix", "restore_" + stem]
    p = subprocess.run(cmd, cwd=HERE, capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    sys.stdout.write(p.stdout or "")
    if p.stderr:
        sys.stderr.write(p.stderr)
    return p.returncode


if __name__ == "__main__":
    only = sys.argv[1:] or list(SIZES)
    rc = 0
    for n in only:
        rc |= run(n)
    sys.exit(rc)